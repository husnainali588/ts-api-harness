// Post-hook: keeps the template's src/routes/index.ts (harness-generated) listing every route module, so
// createApp() always mounts all routes. Only acts on APIs scaffolded from the template (marker comment present).
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { defineHook } from '../../../core/sdk.js';

export const MARKER = '// Generated by the harness from src/routes/*.ts — do not edit.';

export function renderIndex(modules: string[]): string {
  const idents = modules.map((m) => m.replace(/[^a-zA-Z0-9]+(.)/g, (_s, c: string) => c.toUpperCase()).replace(/^[^a-zA-Z_]/, '_$&'));
  const imports = modules.map((m, i) => `import ${idents[i]} from './${m}.js';`);
  return [
    `${MARKER} Each route module default-exports an array of`,
    '// routes made with defineRoute.',
    "import type { AnyRoute } from '../http/route.js';",
    ...imports,
    '',
    `export const routes: readonly AnyRoute[] = [${idents.map((i) => `...${i}`).join(', ')}];`,
    '',
  ].join('\n');
}

export default defineHook({
  id: 'route-index',
  phase: 'post',
  order: 950,
  matches: (_call, ctx) =>
    ctx.tool.writes === true && ctx.output?.isError !== true && (ctx.output?.wrote ?? []).some((p) => /^src\/routes\/[^/]+\.ts$/.test(p) && !p.endsWith('index.ts')),
  run(_call, ctx) {
    const dir = ctx.resolvePath('src/routes');
    const index = join(dir, 'index.ts');
    if (!existsSync(index) || !readFileSync(index, 'utf8').startsWith(MARKER)) return { decision: 'pass' };
    const modules = readdirSync(dir)
      .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !/\.(test|spec)\.ts$/.test(f))
      .map((f) => f.slice(0, -3))
      .sort();
    const next = renderIndex(modules);
    if (readFileSync(index, 'utf8') === next) return { decision: 'pass' };
    writeFileSync(index, next);
    return { decision: 'record', note: `regenerated src/routes/index.ts with ${modules.join(', ') || 'no modules'}` };
  },
});
